"""Generate examples/MADOUN_EXAMPLE.md by running the checklist engine on examples/madoun_answers.json.
Hypothetical worked example. Madoun is a synthetic prototype and is not deployed."""
import json
from pathlib import Path
from . import engine

ROOT = Path(__file__).resolve().parents[2]

ASSUMED = {
    "system_type": "Assumed: a learned risk scoring model that ranks customs declarations for officer review.",
    "audience": "Assumed: officers only.",
    "decision_impact": "Assumed: the score is a principal input to choosing which consignments are held for inspection, and an officer decides. This is a hypothetical setting.",
    "acquisition": "Assumed: built in house (as the prototype is).",
    "eu_market": "Assumed: no.",
}
LEFT_OUT = {
    "data_types": "Left unanswered on purpose: the prototype uses synthetic data, and real declarations may carry personal data about traders or individuals. The data owner would have to say.",
    "hosting": "Left unanswered on purpose: nothing is deployed, so there is no location.",
    "entity_zone": "Left unanswered on purpose: which authority and which instrument family would apply is exactly what a real deployer would have to establish, with legal review.",
}

def main():
    ans = json.load(open(ROOT / "examples/madoun_answers.json", encoding="utf-8"))
    res = engine.run(ans)
    schema = engine.load_schema()
    L = ["# Worked example: customs clearance decision support (hypothetical)", "",
         "> **Hypothetical.** Madoun is a synthetic prototype built as a learning project. It is not deployed. No customs or other authority uses, has reviewed, or endorses it, and nothing here describes a real authority's process. The answers below are assumptions chosen to illustrate the tool.",
         "> **Research aid, not legal advice.** Applicability here is the maintainer's proposal built from retrieved sources. UNKNOWN means the answers do not settle the item.", "",
         "Generated by `python -m ikhtibar.build_example` from `examples/madoun_answers.json`. Re run it after the evidence table changes.", "",
         "## 1. Answers", "", "| Question | Answer | Note |", "|---|---|---|"]
    for k in schema["questions"]:
        if k in ans:
            L.append(f"| {k} | `{ans[k]}` | {ASSUMED.get(k, '')} |")
        else:
            L.append(f"| {k} | (unknown) | {LEFT_OUT.get(k, 'Left unanswered.')} |")
    s = res["summary"]
    L += ["", f"## 2. Result: {s['APPLIES']} items apply, {s['DOES_NOT_APPLY']} do not apply, {s['UNKNOWN']} are UNKNOWN", ""]
    for state, title in [("APPLIES", "Items that apply"), ("UNKNOWN", "Items that are UNKNOWN, and what would close them"), ("DOES_NOT_APPLY", "Items that do not apply")]:
        its = [i for i in res["items"] if i["state"] == state]
        L += [f"### {title} ({len(its)})", ""]
        if not its:
            L += ["None.", ""]; continue
        if state == "UNKNOWN":
            L += ["| Item | Needs | How it could be closed |", "|---|---|---|"]
            for i in its:
                need = i["to_settle"] or ["a decision by the system owner (the answers given do not settle it)"]
                close = "; ".join(schema["questions"][k]["settle_by"] for k in i["to_settle"]) if i["to_settle"] else i.get("close_by", "Read the item's reason and decide with the system owner.")
                L.append(f"| **{i['id']}** {i['text']} | {', '.join(need)} | {close} |")
        else:
            L += ["| Item | Reason | Test evidence templates (proposals) |", "|---|---|---|"]
            for i in its:
                L.append(f"| **{i['id']}** {i['text']} | {i['why']} | {', '.join(i['templates'])} |")
        L.append("")
    # binding trace summary
    yes = sorted({(x["row_id"]) for i in res["items"] for x in i["sources"] if x["binds_you"] == "YES"})
    unk_bind = sorted({(x["row_id"]) for i in res["items"] for x in i["sources"] if x["binds_you"] == "UNKNOWN" and x["source_binding_status"] in ("mandatory", "conditional")})
    L += ["## 3. Does any cited source bind this system?", "",
          f"- Rows where the answers settle that a source binds the entity: **{len(yes)}** ({', '.join('`'+r+'`' for r in yes) or 'none'}).",
          f"- Mandatory or conditional rows whose binding force on the entity is **UNKNOWN** with these answers: **{len(unk_bind)}**. Settling the entity zone (and, for some, scope or trigger questions) would turn many of them into yes or no.",
          "- All guidance and voluntary rows are not binding by their own terms.", "",
          "## 4. What a first test plan would use", "",
          "Templates are proposals in `templates/test_evidence/`:", ""]
    tpl = sorted({t for i in res["items"] if i["state"] == "APPLIES" for t in i["templates"]})
    L += [f"- `{t}`" for t in tpl]
    L += ["", "## 5. What this example does not show", "",
          "- It does not say which authority would be responsible, which instruments bind it, or whether any approval is needed. Those are the UNKNOWN items.",
          "- It does not assess Madoun's actual performance or fairness. Those tests have not been run on real data.",
          "- Items marked with a verification status other than VERIFIED in the full output (`python -m ikhtibar.cli --answers examples/madoun_answers.json`) rest on sources that could not be re checked.", ""]
    (ROOT / "examples" / "MADOUN_EXAMPLE.md").write_text("\n".join(L), encoding="utf-8")
    print("example written;", s)

if __name__ == "__main__":
    main()
